import {readFile,writeFile,mkdir} from 'node:fs/promises';
import * as THREE from '../../dist/vendor/three/build/three.module.js';
import {createElevationSampler} from '../../dist/elevation-profile.js';
import {specifications} from './specs.mjs';
for(const spec of specifications){
 const registered=JSON.parse(await readFile(new URL('../'+spec.slug+'/source/registered-reference.json',import.meta.url),'utf8'));
 if(registered.determinant!==1||registered.registrationRmsMeters>15)throw Error(spec.slug+' geographic registration rejected');
 const raw=registered.points.map(([x,z])=>new THREE.Vector3(x,0,z));
 if(raw[0].distanceTo(raw.at(-1))<.1)raw.pop();
 const input=new THREE.CatmullRomCurve3(raw,true,'centripetal');input.arcLengthDivisions=16000;input.updateArcLengths();
 const n=Math.ceil(spec.length/3),spacing=input.getLength()/n,sigma=spec.slug==='monaco'?5:7,radius=Math.ceil(sigma*3/spacing);
 const uniform=Array.from({length:n},(_,i)=>input.getPointAt(i/n));
 const weights=Array.from({length:radius*2+1},(_,i)=>Math.exp(-.5*((i-radius)*spacing/sigma)**2));
 const total=weights.reduce((a,b)=>a+b,0);
 const points=uniform.map((_,i)=>weights.reduce((p,w,j)=>p.addScaledVector(uniform[(i+j-radius+n)%n],w/total),new THREE.Vector3()));
 const plan=new THREE.CatmullRomCurve3(points,true,'centripetal');plan.arcLengthDivisions=16000;plan.updateArcLengths();
 const samples=Array.from({length:n},(_,i)=>plan.getPointAt(i/n));
 const turns=Object.fromEntries(registered.corners.map(c=>{
  let best=0,d=Infinity;for(let i=0;i<n;i++){const q=Math.hypot(samples[i].x-c.x,samples[i].z-c.z);if(q<d){d=q;best=i;}}
  return ['T'+c.number,{number:c.number,name:'Virage '+c.number,u:best/n,station:best/n*spec.length}];
 }));
 if(Object.keys(turns).length!==spec.turnCount)throw Error(spec.slug+' corner count');
 const profile=spec.heights.map(([anchor,y])=>[typeof anchor==='string'?turns[anchor].u*spec.length:anchor*spec.length,y]).sort((a,b)=>a[0]-b[0]);
 profile.push([spec.length,profile[0][1]]);
 const elevation=createElevationSampler(profile,{lapLength:spec.length,baseY:2,presentationScale:spec.reliefScale});
 const sourcePoints=samples.map((p,i)=>new THREE.Vector3(p.x,elevation(i/n*spec.length),p.z));
 let scale=1;const curve=new THREE.CatmullRomCurve3(sourcePoints,true,'centripetal');curve.arcLengthDivisions=16000;
 for(let pass=0;pass<5;pass++){curve.updateArcLengths();const correction=spec.length/curve.getLength();scale*=correction;for(const p of sourcePoints){p.x*=correction;p.z*=correction;}}
 curve.updateArcLengths();
 const output=Array.from({length:n},(_,i)=>curve.getPointAt(i/n).toArray().map(v=>+v.toFixed(5)));output.push(output[0]);
 // Reproject each independently labelled turn into the final geographic plan.
 for(const [id,turn] of Object.entries(turns)){
  const reference=registered.corners.find(c=>c.number===turn.number);let best=0,d=Infinity;
  for(let i=0;i<n;i++){const q=Math.hypot(output[i][0]-reference.x*scale,output[i][2]-reference.z*scale);if(q<d){d=q;best=i;}}
  turn.u=best/n;turn.station=best/n*spec.length;turn.position=output[best];
 }
 const config={...spec,geography:{origin:registered.origin,metresPerDegree:registered.metresPerDegree,scale,determinant:1,registrationRmsMeters:registered.registrationRmsMeters},turns,elevationProfile:profile,source:{plan:'WGS84 bacinger/f1-circuits (MIT)',annotations:'MultiViewer circuit API; underlying candidate-lap year may differ from requested metadata year',requestedYear:registered.sourceYear},simulation:'illustrative'};
 delete config.heights;
 if(spec.slug==='monaco'){
  const lane=JSON.parse(await readFile(new URL('../monaco/pit-lane.json',import.meta.url),'utf8'));
  config.pitGeographic=lane.map(([lon,lat],i)=>{
   const x=(lon-registered.origin[0])*registered.metresPerDegree[0]*scale,z=-(lat-registered.origin[1])*registered.metresPerDegree[1]*scale;
   let best=0,d=Infinity;for(let j=0;j<n;j++){const q=Math.hypot(output[j][0]-x,output[j][2]-z);if(q<d){d=q;best=j;}}
   const before=output[(best-2+n)%n],after=output[(best+2)%n],vx=after[0]-before[0],vz=after[2]-before[2],norm=Math.hypot(vx,vz);
   const ease=t=>{t=Math.max(0,Math.min(1,t));return t*t*(3-2*t);};
   const offset=-8*ease((i-25)/6)*(1-ease((i-46)/3));
   return [lon+offset*vz/norm/registered.metresPerDegree[0]/scale,lat+offset*vx/norm/registered.metresPerDegree[1]/scale];
  });
 }
 const directory=new URL('../../dist/'+spec.slug+'/',import.meta.url);await mkdir(directory,{recursive:true});
 await writeFile(new URL('config.json',directory),JSON.stringify(config,null,2)+'\n');
 await writeFile(new URL('track-data.js',directory),'// Generated by scripts/season-2026/build-tracks.mjs. x=east, z=south; no reflection.\nexport const TRACK_POINTS='+JSON.stringify(output)+';\nexport const CONFIG='+JSON.stringify(config)+';\n');
 console.log(spec.slug,'length',curve.getLength().toFixed(3),'scale',scale.toFixed(6),'turn stations',Object.values(turns).map(t=>Math.round(t.station)).join(','));
}
